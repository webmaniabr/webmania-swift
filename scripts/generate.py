#!/usr/bin/env python3
"""Generate Swift DTOs from pinned vendored contracts; stdlib only, deterministic."""
import argparse, hashlib, json, pathlib, re
ROOT=pathlib.Path(__file__).resolve().parents[1]
# contract_digest = SHA-256 of the canonical JSON of the sorted module path -> SHA-256 mapping.
DIGEST='371a499f74012bb6b41f23642869dee4954e8394dcba7642edc701aedb3dd59e'
SOURCE=ROOT.parent/'webmania-openapi'
def contract_digest(locks):return hashlib.sha256(json.dumps({x['path']:x['sha256'] for x in locks},sort_keys=True,separators=(',',':')).encode()).hexdigest()
def upper(s):
 n=''.join(x[:1].upper()+x[1:] for x in re.split('[^A-Za-z0-9]+',s) if x)
 return ('N'+n if n[:1].isdigit() else n) or 'Value'
def q(s):return json.dumps(s,ensure_ascii=False)
def prop(s):return '`'+re.sub('[^A-Za-z0-9_]','_',('field_'+s if s[:1].isdigit() else s))+'`'
def generate(vendor=False,source=SOURCE):
 outputs={}; resources=ROOT/'Sources/Webmania/Resources/contracts'
 def pinned(p):return (pathlib.Path(source)/p).read_bytes()
 manifest=pinned('contracts/manifest.json') if vendor else (resources/'manifest.json').read_bytes()
 outputs['Sources/Webmania/Resources/contracts/manifest.json']=manifest
 allops=[]; catalog=[]; locks=[]; count=0;schemafiles={}
 facade=['// Generated by scripts/generate.py.','import Foundation','extension WebmaniaClient {']
 for path in json.loads(manifest)['contracts']:
  module=path.removeprefix('contracts/').replace('/','_').replace('.openapi.json','').replace('-','_')
  prefix=upper(module);raw=pinned(path) if vendor else (resources/(module+'.json')).read_bytes();doc=json.loads(raw)
  outputs['Sources/Webmania/Resources/contracts/'+module+'.json']=raw
  locks.append({'path':path,'module':module,'sha256':hashlib.sha256(raw).hexdigest()})
  schemas=doc['components']['schemas'];pending={};done={};aliases={};lines=['// Generated; exact JSON property names and branch-local projections.','import Foundation']
  def register(n,s):
   if n in pending and pending[n]!=s:n+=hashlib.sha256(json.dumps(s,sort_keys=True).encode()).hexdigest()[:8]
   pending[n]=s;return n
  def ownprops(s,seen=frozenset()):
   p={}
   if '$ref'in s:
    n=s['$ref'].split('/')[-1]
    if n not in seen:p.update(ownprops(schemas[n],seen|{n}))
   for sub in s.get('allOf',[]):p.update(ownprops(sub,seen))
   p.update(s.get('properties',{}));return p
  def typ(s,n,force=False):
   if '$ref'in s and len([k for k in s if not k.startswith('x-') and k not in ('$ref','description')])==0:
    return prefix+upper(s['$ref'].split('/')[-1])
   t=s.get('type')
   if t is None and ('enum'in s or 'const'in s):
    types=[]
    for v in s.get('enum',[s.get('const')]):
     z='null'if v is None else 'boolean'if isinstance(v,bool)else 'integer'if isinstance(v,int)else 'number'if isinstance(v,float)else 'string'
     if z not in types:types.append(z)
    if len(types)==1:t=types[0]
    else:s=dict(s,type=types);t=types
   if t=='object' or 'properties'in s or ownprops(s):return register(n,s)
   if 'anyOf'in s or 'oneOf'in s or isinstance(t,list):return register(n,s)
   if t=='array':return '['+typ(s.get('items',{}),n+'Item')+']'
   return {'string':'String','integer':'JSONInteger','number':'JSONNumber','boolean':'Bool'}.get(t,'JSONValue')
  for n,s in schemas.items():
   name=prefix+upper(n);t=typ(s,name,True)
   if t!=name:aliases[name]=t;pending[name]=s
  for route,item in doc['paths'].items():
   for verb,op in item.items():
    if not isinstance(op,dict)or'operationId'not in op:continue
    oid=op['operationId'];name=upper(oid);pn=name+'Parameters'
    params=item.get('parameters',[])+op.get('parameters',[])
    ps={'type':'object','properties':{p['name']:p['schema']for p in params},'required':[p['name']for p in params if p.get('required')],'additionalProperties':False}
    body=op.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema')
    if body is not None:
     ps['properties']['body']=body
     if op['requestBody'].get('required'):ps['required'].append('body')
    register(pn,ps)
    successes={k:v for k,v in op['responses'].items() if k.startswith('2')}
    jsons=[v['content']['application/json']['schema']for v in successes.values()if'application/json'in v.get('content',{})]
    file=any(media!='application/json'for v in successes.values()for media in v.get('content',{}))
    rt=typ(jsons[0],name+'Result')if jsons else'JSONValue'
    security=op.get('security',doc.get('security',[]))
    allops.append({'id':oid,'module':module,'verb':verb.upper(),'path':route,'origin':doc['servers'][0]['url'],'parameters':params,'requestSchema':pn,'responses':op['responses'],'security':security,'schemes':doc.get('components',{}).get('securitySchemes',{}),'enabled':op.get('x-sdk-generation-enabled',True),'effects':op.get('x-operation-effects',{}),'hasBody':body is not None,'file':file})
    invoke='executeFile'if file else'execute'
    signature='public func '+oid+'(_ parameters: '+pn+' = '+pn+'()) async throws -> '+('FileResult<'+rt+'>'if file else'APIResponse<'+rt+'>')+' {'
    facade += ['    '+signature,'        try await '+invoke+'('+q(oid)+', parameters: parameters'+(', as: '+rt+'.self')+')','    }']
  while len(done)<len(pending):
   name=next(n for n in pending if n not in done);s=pending[name];done[name]=s;p=ownprops(s)
   obj=s.get('type')=='object'or'properties'in s or bool(p)
   if name in aliases:lines+=['public typealias '+name+' = '+aliases[name]]
   elif obj:
    lines+=['public struct '+name+': JSONModel {','    public static let module = '+q(module),'    public static let schemaID = '+q(name),'    public static let knownFields: Set<String> = ['+', '.join(q(k)for k in p)+']','    public private(set) var storage: [String: JSONValue] = [:]','    public init() {}','    public init(json: JSONValue) throws { try Contracts.validate(json, module: Self.module, schema: Self.schemaID); guard case .object(let o) = json else { throw ModelError.invalidType }; storage = o }','    public mutating func setAdditionalField(_ key: String, value: JSONValue?) throws { guard !Self.knownFields.contains(key) else { throw ModelError.constraint }; storage[key] = value }']
    seen=set()
    for k,sub in p.items():
     pn=prop(k)
     if pn in seen:pn=prop(k+'_'+hashlib.sha256(k.encode()).hexdigest()[:6])
     seen.add(pn);t=typ(sub,name+upper(k));lines+=['    public var '+pn+': Field<'+t+'> {','        get { Field.read(storage['+q(k)+']) }','        set { storage['+q(k)+'] = newValue.raw }','    }']
    # Common fields stay typed; alternatives apply their own constraints only when explicitly selected.
    for kind in ['anyOf','oneOf']:
     for i,sub in enumerate(s.get(kind,[])):
      t=typ(sub,name+'Branch'+str(i+1));lines+=['    public func asBranch'+str(i+1)+'() throws -> '+t+' { try Contracts.validate(json, module: Self.module, inline: '+q(name)+', branch: '+str(i)+', kind: '+q(kind)+'); return try '+t+'(json: json) }']
    lines+=['}']
   elif 'anyOf'in s or'oneOf'in s or isinstance(s.get('type'),list):
    variants=s.get('anyOf',s.get('oneOf',[dict(s,type=t)for t in s['type']]if isinstance(s.get('type'),list)else[]))
    lines+=['public struct '+name+': JSONRepresentable, CustomStringConvertible, CustomDebugStringConvertible {','    public let json: JSONValue','    public init(json: JSONValue) throws { try Contracts.validate(json, module: '+q(module)+', schema: '+q(name)+'); self.json = json }','    public var description: String { "[Webmania typed union content withheld]" }','    public var debugDescription: String { description }']
    for i,sub in enumerate(variants):
     t=typ(sub,name+'Variant'+str(i+1))
     if t==name:continue
     lines+=['    public init(variant'+str(i+1)+': '+t+') throws { try self.init(json: variant'+str(i+1)+'.json) }','    public func asVariant'+str(i+1)+'() throws -> '+t+' { try Contracts.validate(json, module: '+q(module)+', inline: '+q(name)+', branch: '+str(i)+', kind: '+q('anyOf'if'anyOf'in s else'oneOf'if'oneOf'in s else'type')+'); return try '+t+'(json: json) }']
    lines+=['}']
   else:lines+=['public typealias '+name+' = '+typ(s,name+'Value')]
   catalog.append({'module':module,'name':name,'fields':list(p),'kind':'alias'if name in aliases else'object'if obj else'union'})
   count+=1
  outputs['Sources/Webmania/Generated/'+prefix+'.swift']=('\n'.join(lines)+'\n').encode()
  # Schema validation uses the complete original compositions, never a flattened merge.
  schemafiles[module]={'components':schemas,'generated':pending}
 facade+=['}'];outputs['Sources/Webmania/Generated/Operations.swift']=('\n'.join(facade)+'\n').encode()
 for module,schemas in schemafiles.items():outputs['Sources/Webmania/Resources/contracts/'+module+'-schemas.json']=(json.dumps(schemas,ensure_ascii=False,separators=(',',':'))+'\n').encode()
 outputs['Sources/Webmania/Resources/contracts/operations.json']=(json.dumps(allops,ensure_ascii=False,separators=(',',':'))+'\n').encode()
 if contract_digest(locks)!=DIGEST:raise SystemExit('contract_digest differs from the pinned value')
 outputs['contracts.lock.json']=(json.dumps({'repository':'https://github.com/webmaniabr/webmania-openapi','contract_digest':DIGEST,'modules':locks,'operations':len(allops),'enabled':sum(o['enabled']for o in allops),'generated_types':count},indent=2)+'\n').encode()
 outputs['model-catalog.json']=(json.dumps(catalog,indent=2)+'\n').encode()
 return outputs
if __name__=='__main__':
 ap=argparse.ArgumentParser();ap.add_argument('--vendor',action='store_true',help='reimport the contracts from a webmania-openapi checkout whose modules match contract_digest');ap.add_argument('--openapi',default=str(SOURCE));ap.add_argument('--check',action='store_true');args=ap.parse_args();outputs=generate(args.vendor,args.openapi)
 stale=[]
 for path,data in outputs.items():
  dest=ROOT/path
  if args.check:
   if not dest.exists()or dest.read_bytes()!=data:stale.append(path)
  else:dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(data)
 generated=set(str(p.relative_to(ROOT))for p in (ROOT/'Sources/Webmania/Generated').glob('*.swift'))
 extras=generated-set(outputs)
 if extras:stale.extend(sorted(extras))
 if stale:raise SystemExit('Generation differs: '+', '.join(stale))
 print('Reproducible'if args.check else'Generated',len(outputs),'files')
